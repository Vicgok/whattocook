export const ingredients: Ingredient[] = definitions.flatMap(
  ([categoryId, items]) =>
    items.map((def) => ({
      id: slug(def.name),
      slug: slug(def.name),
      name: def.name,
      categoryId,
      subcategory: def.subcategory ?? null,
      aliases: def.aliases ?? [],
      searchKeywords: def.keywords ?? [],
      defaultUnit: def.unit ?? (def.countable ? "piece" : null),
      isCountable: def.countable ?? false,
      pantryCommon: def.common ?? true,
      parentIngredientId: def.parent ?? inferredParent(def.name),
    })),
);
export const ingredientsById = new Map(
  ingredients.map((ingredient) => [ingredient.id, ingredient]),
);
